#!/usr/bin/env bash
# setup.sh — Interactive setup for memdb-memory plugin
set -euo pipefail

CONFIG_DIR="${HOME}/.config/claude-code-memdb"
CONFIG_FILE="${CONFIG_DIR}/config.env"

echo ""
echo "=== memdb-memory plugin setup ==="
echo ""
echo "This will configure your MemDB connection for Claude Code."
echo "Config will be saved to: ${CONFIG_FILE}"
echo ""

# --- Prompt for values ---

read -rp "MemDB API URL [http://127.0.0.1:8080]: " api_url
api_url="${api_url:-http://127.0.0.1:8080}"

read -rp "Person ID (human identity) [krolik]: " person_id
person_id="${person_id:-krolik}"

read -rp "Cube ID (memory partition) [memos]: " cube_id
cube_id="${cube_id:-memos}"

read -rp "Internal service secret (optional, press Enter to skip): " secret
secret="${secret:-}"

# --- Test connectivity ---

echo ""
echo "Testing connection to ${api_url}/health ..."

if curl -sf --max-time 5 "${api_url}/health" > /dev/null 2>&1; then
  echo "OK — MemDB is reachable."
else
  echo "WARNING: Could not reach ${api_url}/health"
  echo "The config will still be saved. You can re-run setup.sh later."
  read -rp "Continue anyway? [Y/n]: " cont
  if [[ "${cont,,}" == "n" ]]; then
    echo "Aborted."
    exit 1
  fi
fi

# --- Write config ---

mkdir -p "${CONFIG_DIR}"
cat > "${CONFIG_FILE}" <<EOF
# memdb-memory plugin configuration
# Generated by setup.sh on $(date -Iseconds)
MEMDB_API_URL=${api_url}
MEMDB_PERSON_ID=${person_id}
MEMDB_CUBE_ID=${cube_id}
EOF

if [[ -n "${secret}" ]]; then
  echo "INTERNAL_SERVICE_SECRET=${secret}" >> "${CONFIG_FILE}"
fi

chmod 600 "${CONFIG_FILE}"

echo ""
echo "Config saved to ${CONFIG_FILE}"
echo ""
echo "Next steps:"
echo "  1. Restart Claude Code (or start a new session)"
echo "  2. You should see 'MemDB memory connected' at session start"
echo "  3. Your memories will be automatically injected on each prompt"
echo ""
echo "To reconfigure, run this script again."
echo "To uninstall, delete ${CONFIG_DIR}"
echo ""
